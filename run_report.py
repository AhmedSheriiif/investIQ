"""
InvestIQ Phase 0 - Full Pipeline

ticker -> fetch price history -> compute risk metrics -> AI narrative -> saved report

This is the complete Phase 0 deliverable: a single-command tool that produces
a readable risk report for any ticker (or small list of tickers), benchmarked
against SPY by default.

Usage:
    python3 run_report.py                  # uses TICKERS list below
    python3 run_report.py NVDA TSLA        # override via command line
"""

import sys
import os
from datetime import datetime

# Windows terminals often default to cp1252, which can't display characters
# like non-breaking hyphens that LLMs sometimes produce. Force UTF-8 output.
if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")

from data_fetcher import fetch_close_prices, BENCHMARK
from risk_metrics import compute_all_metrics
from narrative_generator import generate_risk_narrative, PROVIDER

DEFAULT_TICKERS = ["AAPL", "MSFT"]
OUTPUT_DIR = "reports"


def build_report_for_ticker(ticker: str, benchmark_prices) -> str:
    """Runs the full pipeline for one ticker and returns a formatted markdown report."""
    print(f"\n[{ticker}] Fetching price history...")
    prices = fetch_close_prices(ticker)
    print(f"[{ticker}] {len(prices)} trading days "
          f"({prices.index[0].date()} to {prices.index[-1].date()})")

    print(f"[{ticker}] Computing risk metrics...")
    metrics = compute_all_metrics(prices, benchmark_prices)

    print(f"[{ticker}] Generating AI narrative (provider: {PROVIDER})...")
    narrative = generate_risk_narrative(ticker, metrics)

    report = f"""# Risk Report: {ticker}

**Period:** {metrics['period_start'].date()} to {metrics['period_end'].date()} ({metrics['trading_days']} trading days)
**Current price:** ${metrics['current_price']:.2f}
**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M')}

## Risk Metrics

| Metric | Value |
|---|---|
| Annualized Return | {metrics['annualized_return']*100:.2f}% |
| Annualized Volatility | {metrics['annualized_volatility']*100:.2f}% |
| Sharpe Ratio | {metrics['sharpe_ratio']:.2f} |
| Sortino Ratio | {metrics['sortino_ratio']:.2f} |
| Max Drawdown | {metrics['max_drawdown']*100:.2f}% |
| VaR (95%, daily) | {metrics['var_95']*100:.2f}% |
| VaR (99%, daily) | {metrics['var_99']*100:.2f}% |
| CVaR (95%, daily) | {metrics['cvar_95']*100:.2f}% |
"""
    if "beta" in metrics:
        report += f"| Beta (vs {BENCHMARK}) | {metrics['beta']:.2f} |\n"

    report += f"""
## AI Risk Narrative

{narrative}

---
*Generated by InvestIQ Phase 0. This is an automated risk narrative based on historical
data and does not constitute investment advice.*
"""
    return report


def main():
    tickers = sys.argv[1:] if len(sys.argv) > 1 else DEFAULT_TICKERS

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    print(f"Fetching benchmark ({BENCHMARK})...")
    benchmark_prices = fetch_close_prices(BENCHMARK)
    print(f"  -> {len(benchmark_prices)} trading days")

    for ticker in tickers:
        try:
            report = build_report_for_ticker(ticker, benchmark_prices)

            filename = f"{OUTPUT_DIR}/{ticker}_{datetime.now().strftime('%Y%m%d_%H%M')}.md"
            with open(filename, "w", encoding="utf-8") as f:
                f.write(report)

            print(f"\n[{ticker}] Report saved to {filename}")
            print("=" * 60)
            print(report)
            print("=" * 60)

        except Exception as e:
            print(f"\n[{ticker}] FAILED: {e}")
            continue


if __name__ == "__main__":
    main()